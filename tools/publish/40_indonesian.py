"""More Indonesian, without touching /assets/lang.js.

Writes /assets/lang-extra.js: it adds the strings in id-extra.json (and any
per-page strings in <script id="imr-i18n-page">) to the site dictionary, then
re-applies the chosen language. Strings already in lang.js keep their wording.

On decision pages it also
- splits the "court · country · date · level" and "Type of case: ..." lines into
  pieces the dictionary can translate,
- adds the Indonesian text of each "What happened afterwards" event (from
  data/court-decisions/timeline.csv) as per-page strings,
- hides the English question and plain-language summary in Indonesian view when
  the page has the Indonesian version right below them.
"""
import html as H
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, __file__.rsplit("/", 1)[0])
from common import DATA, SITE, read_csv  # noqa: E402

EXTRA = json.loads((Path(__file__).parent / "id-extra.json").read_text(encoding="utf-8"))
JS = """/* More Indonesian strings (generated by tools/publish/40_indonesian.py; edit id-extra.json). */
(function () {
  var X = %s;
  var S = window.SITE_I18N = window.SITE_I18N || {}, D = S.id = S.id || {};
  function add(o) { Object.keys(o).forEach(function (k) {
    if (k === '__pat') D.__pat = (D.__pat || []).concat(o.__pat);
    else if (!Object.prototype.hasOwnProperty.call(D, k)) D[k] = o[k];
  }); }
  add(X);
  var p = document.getElementById('imr-i18n-page');
  if (p) { try { add(JSON.parse(p.textContent)); } catch (e) {} }
  if (document.getElementById('langs')) return; // the Clinic translates itself
  var b = document.querySelector('.imr-lang button[aria-pressed="true"]');
  if (b && b.getAttribute('data-sl') !== 'en') b.click();
})();
"""
(SITE / "assets" / "lang-extra.js").write_text(JS % json.dumps(EXTRA, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
STYLE = '<style id="imr-id-only">html[lang="id"] .imr-en-only{display:none}</style>'

timeline = {}
for r in read_csv(DATA / "court-decisions" / "timeline.csv"):
    timeline.setdefault(r["decision_id"], []).append(r)

TAG = re.compile(r'(<script src="/assets/lang\.js[^"]*"[^>]*></script>)')
n_pages = n_dec = 0
for page in SITE.rglob("*.html"):
    rel = page.relative_to(SITE)
    if rel.parts[0] in ("api", "press"):
        continue
    html = page.read_text(encoding="utf-8")
    if "lang-extra.js" in html or not TAG.search(html):
        continue
    html = TAG.sub(r'\1\n<script src="/assets/lang-extra.js" defer></script>', html, count=1)
    n_pages += 1
    if rel.parts[:2] == ("court-decisions", "d") and len(rel.parts) == 4:
        did = rel.parts[2]
        # "<b>Court</b> · Kenya · 2011-03-22 · Regional court or body"
        html = re.sub(r"(<p><b>[^<]*</b>)((?: · [^<·]+)+)</p>",
                      lambda m: m.group(1) + "".join(f" · <span>{x.strip()}</span>" for x in m.group(2).split(" · ") if x.strip()) + "</p>",
                      html, count=1)
        # "Citation: X<br>Type of case: Y<br>Outcome: Z"
        html = re.sub(r"(Citation|Type of case|Outcome): ([^<]+)",
                      lambda m: f"<span>{m.group(1)}:</span> " + (f"<span data-noi18n>{m.group(2)}</span>" if m.group(1) == "Citation" else f"<span>{m.group(2)}</span>"),
                      html)
        # breadcrumb "Court Decisions › Kenya"
        html = re.sub(r"(</a>) › ([^<]+)</p>", r"\1 › <span>\2</span></p>", html, count=1)
        # English question and summary hidden when the Indonesian follows
        if 'lang="id"' in html:
            html = re.sub(r"<h2>In plain language</h2><p>", '<h2 class="imr-en-only">In plain language</h2><p class="imr-en-only">', html, count=1)
            if "<b>Pertanyaan:</b>" in html:
                html = re.sub(r"<h2>Question</h2><p>", '<h2 class="imr-en-only">Question</h2><p class="imr-en-only">', html, count=1)
            html = html.replace("</head>", STYLE + "</head>", 1)
        page_dict = {}
        for ev in timeline.get(did, []):
            if ev.get("event_id"):
                for en in (f'{ev["date"]}: {ev["event_en"]}', ev["event_en"]):
                    if H.escape(en, quote=False) in html or en in html:
                        page_dict[en] = (f'{ev["date"]}: ' if en.startswith(ev["date"] + ": ") else "") + ev["event_id"]
        if page_dict:
            blob = json.dumps(page_dict, ensure_ascii=False).replace("</", "<\\/")
            html = html.replace("</body>", f'<script type="application/json" id="imr-i18n-page">{blob}</script>\n</body>', 1)
        n_dec += 1
    page.write_text(html, encoding="utf-8")
print(f"  Indonesian: lang-extra.js on {n_pages} pages ({len(EXTRA)} strings); {n_dec} decision pages prepared")
