// Builds /legal-clinic/trafficking-check/tc-data.js from tc-content.js plus the site's own data
// (Court Decisions, East Asia, Southeast Asia, Gulf States, Migrant Domestic Workers).
// Usage: node build.js SITE      (then python3 page.py SITE)
const vm = require('vm'), fs = require('fs'), path = require('path');
const SITE = process.argv[2] || '/mnt/project-files/theimr-site';
const ctx = {}; ctx.window = ctx; vm.createContext(ctx);
for (const f of ['east-asia/ea-data.js', 'southeast-asia/sea-data.js', 'gcc/gcc-data.js', 'domestic-workers/dw-data.js', 'court-decisions/cd-data.js'])
  vm.runInContext(fs.readFileSync(path.join(SITE, f), 'utf8'), ctx);
const content = fs.readFileSync(path.join(__dirname, 'tc-content.js'), 'utf8');
vm.runInContext(content, ctx);
const { EA, SEA, GCC, DW, CD, TC } = ctx;

// ---- destination data pulled from site datasets ----
const st = v => !v ? 'n' : v === '?' ? '?' : (/^[pad]/.test(v) ? 'p' : v === 's' ? 's' : 'p');
const yr = v => (v && v.match(/\d{4}/) || [''])[0];
const GRP = { // which coded worker group to read, by sector
  MY: { domestic: 'MY-DW', farm: 'MY-PLT', _: 'MY-PLT' }, SG: { domestic: 'SG-MDW', _: 'SG-WP' },
  TH: { farm: 'TH-AGR', fishing: 'TH-FSH', _: 'TH-MOU' }, BN: { _: 'BN-FW' },
  HK: { _: 'HK-FDH' }, TW: { fishing: 'TW-DWF', _: 'TW-C' }, JP: { _: 'JP-TITP' }, KR: { fishing: 'KR-E10', _: 'KR-E9' }
};
const D = {};
for (const k of Object.keys(TC.DEST)) {
  const o = { tr: {}, laws: [], mob: {}, dw: null, comp: null };
  const intl = (EA.intl[k] || SEA.intl[k]);
  if (intl) {
    for (const t of ['palermo', 'c29', 'p29', 'c105', 'c189', 'icrmw']) o.tr[t] = [st(intl[t]), yr(intl[t])];
  } else {
    const g = GCC.states.find(s => s.k === k);
    const not = (g.ilo_not || '').split(/,\s*/);
    o.tr.c29 = [not.includes('C029') ? 'n' : 'p', ''];
    o.tr.c105 = [not.includes('C105') ? 'n' : 'p', ''];
    o.tr.c189 = [not.includes('C189') ? 'n' : 'p', ''];
    o.tr.p29 = [/ratified|in force/.test(g.p29 || '') ? 'p' : 'n', yr(g.p29)];
    o.tr.icrmw = ['n', ''];
    o.tr.palermo = [TC.PAL_EXTRA[k] || '?', '', 1];
  }
  if (k === 'BN' && TC.PAL_EXTRA.BN && o.tr.palermo[0] === '?') o.tr.palermo = [TC.PAL_EXTRA.BN, '', 1];
  const L = [...(EA.laws || []), ...(SEA.laws || []), ...(GCC.laws || [])].filter(l => l.s === k && /traffick|domestic work/i.test(l.topic + ' ' + l.title));
  o.laws = L.map(l => ({ t: l.title, no: l.no || '', y: l.year, am: l.amended || '', u: l.url || '', topic: l.topic }));
  const st2 = [...EA.states, ...SEA.states].find(s => s.k === k);
  const g = GCC.states.find(s => s.k === k);
  if (st2) o.comp = { en: st2.complaints, id: st2.complaints_id };
  if (g) { o.comp = { en: g.complaints, id: g.complaints_id }; o.mob._ = { en: g.mob_t, id: g.mob_t_id, src: 'Gulf States data' }; }
  const groups = [...EA.groups, ...SEA.groups];
  if (GRP[k]) for (const [sec, gk] of Object.entries(GRP[k])) {
    const gr = groups.find(x => x.k === gk); if (!gr) continue;
    o.mob[sec] = { en: gr.codes.mob[1], src: gr.codes.mob[2], grp: { en: gr.n, id: gr.n_id }, fee: gr.codes.fees ? gr.codes.fees[1] : '' };
  }
  const dc = DW.dc[k];
  if (dc) o.dw = { cov: dc.cov && dc.cov[1], doc: dc.doc && dc.doc[1], mob: dc.mob && dc.mob[1], viol: dc.viol && dc.viol[1], src: [dc.cov && dc.cov[2], dc.doc && dc.doc[2]].filter(Boolean).join('; ') };
  D[k] = o;
}

// ---- court decisions used by the check ----
const ids = new Set(Object.values(TC.CASES).flat());
const C = {};
for (const d of CD.decisions) if (ids.has(d.id)) {
  C[d.id] = { n: d.name, c: d.court, cc: d.cc, y: (d.date || '').slice(0, 4), tier: d.tier, reg: d.region, out: d.outcome, st: d.status, p: d.plain, pi: d.plain_id };
}
const miss = [...ids].filter(i => !C[i]); if (miss.length) console.log('missing decisions:', miss.join(', '));
const out = content + '\n/* ---- generated by build.js from the site data, ' + new Date().toISOString().slice(0, 10) + ' ---- */\nTC.D = ' + JSON.stringify(D) + ';\nTC.CD = ' + JSON.stringify(C) + ';\nTC.CDV = ' + JSON.stringify(CD.version + ' (' + CD.date + ')') + ';\n';
const dir = path.join(SITE, 'legal-clinic/trafficking-check'); fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, 'tc-data.js'), out);
fs.copyFileSync(path.join(__dirname, 'tc.js'), path.join(dir, 'tc.js'));
console.log('tc-data.js', out.length, 'bytes;', Object.keys(D).length, 'destinations;', Object.keys(C).length, 'decisions');
