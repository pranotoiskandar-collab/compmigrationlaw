#!/usr/bin/env python3
"""Turn the iMac official-text check (imac-check/site-codings-check.csv, 13 Nov 2026) into sea-check.js.

sea-check.js loads after sea-data.js (and after oc-sea.js on the origin pages). It sets SEA.checked and OC.checked,
replaces notes with the official-text findings, adds the official link to each source, and applies the recodes
decided below. Status rule (Pranoto, 13 Nov 2026): legislation + confirmed/differs -> "confirmed"; legislation + partly
-> "partly"; ministry or agency page ("official guidance") -> "partly"; secondary/inferred or not found -> stays S.
Editor questions go to imac-check/editor-questions.csv for Pranoto.
"""
import csv, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
rows = list(csv.DictReader(open(os.path.join(HERE, "imac-check", "site-codings-check.csv"), encoding="utf-8-sig")))

# Coder decisions on rows where the check found a different value or left the choice to the editor.
# value None = unclear. Keys not listed keep the coded value.
RECODE = {
    ("MY-DW", "hours"): 1,      # weekly rest day s. 59 since 2023; hours limits still excluded
    ("SG-WP", "mob"): 1,        # MOM: new permit without consent 40-21 days before expiry (official guidance)
    ("TH-MOU", "fees"): 2,      # RO 2017 ss. 42, 49
    ("TH-AGR", "fees"): 2,
    ("TH-FSH", "ins"): 2,       # SSA covers year-round vessels; seasonal fishing excluded (noted)
    # TH-AGR ins stays 1: the group as defined includes seasonal farm workers, whom Royal Decree 2017 s. 3(6)-(7) excludes
    ("BN-FW", "lab"): 2,        # group narrowed to construction and farm workers; domestic workers excluded by s. 2
    ("BN-FW", "mob"): 1,        # s. 24: worker's consent + Commissioner's endorsement
    ("BN-FW", "union"): 1,      # TUA s. 16(3)
    ("BN-FW", "fam"): 1,        # Immigration Regs reg. 16(1), discretionary, wife and children only
    ("MM", "exit"): 1,          # statute sex-neutral; post-2021 measures not verifiable in official texts
    ("MM", "return"): 1,
    ("KH", "welfare"): 1,       # agency deposit covers repatriation and some risks
    ("LA", "welfare"): 1,       # Decree 245/2020 Art. 11(7) fund; benefits not found
    # LA contract stays 1: no state-set minimum terms found
    # TL rec stays unclear: placement is public (SEFOPE), the feature does not apply in the usual way
    ("TL", "contract"): 0,
    ("TL", "predep"): 1,
    ("TL", "welfare"): 0,
}
ORIGINS = {"MM", "KH", "LA", "TL"}
BOILER = re.compile(r"\s*The source for this point \(Ministry of Manpower guidance\).*?was not consulted\.", re.S)


def clean(note):
    note = re.sub(r"^Merged from BN-GEN \(construction and agriculture\); BN-DW shown where domestic workers differ\.\s*", "", note)
    note = re.sub(r"^Mapped from the general Thai rules checked for TH-AGR \(Royal Ordinance 2017, Labour Relations Act, Immigration Act\); sector rules for farm work do not apply to MOU workers in other sectors\.\s*", "", note)
    note = BOILER.sub("", note)
    q = ""
    m = re.search(r"\s*Editor question:\s*(.*)$", note, re.S)
    if m:
        q = m.group(1).strip()
        note = note[:m.start()]
    note = re.sub(r"\s*Official guidance supports [^:]*:\s*", " Official guidance: ", note)
    return note.strip(), q


def status(r):
    f, tier = r["finding"], r["source_tier"]
    if f == "not found" or tier in ("", "secondary or inferred"):
        return None
    if tier == "official guidance":
        return "partly"
    return "partly" if f == "partly" else "confirmed"


sea_checked, oc_checked, upd, questions = {}, {}, [], []
for r in rows:
    g, f = r["group"], r["feature"]
    note, q = clean(r["note"])
    st = status(r)
    key = (g, f)
    if q:
        questions.append({"group": g, "feature": f, "coded": r["coded_value"], "check_finding": r["finding"], "source_tier": r["source_tier"], "question": q, "official_link": r["official_link"]})
    if st is None:
        continue
    tier = "official guidance" if r["source_tier"] == "official guidance" else "official text"
    link = r["official_link"]
    u = {"g": g, "f": f, "note": note, "src_add": (" · " + tier + ": " + link) if link else ""}
    if key in RECODE:
        u["v"] = RECODE[key]
    upd.append(u)
    (oc_checked if g in ORIGINS else sea_checked)[g + "." + f] = st

js = """/* Official-text check of 13 November 2026 (Pranoto's iMac, official legislation sites only; ministry and agency pages cited
   as official guidance and marked "partly"). Generated by southeast-asia-build/apply_check.py from
   imac-check/site-codings-check.csv: do not edit by hand. Loaded after sea-data.js and oc-sea.js. */
(function () {
  var U = %s, SC = %s, OCC = %s;
  function apply(G, isOC) {
    U.forEach(function (u) {
      var c = isOC ? ((G.codes || {})[u.g] || {})[u.f] : (function () { var g = (G.groups || []).filter(function (x) { return x.k === u.g; })[0]; return g && g.codes[u.f]; })();
      if (!c) return;
      if ("v" in u) c[0] = u.v;
      if (u.note) c[1] = u.note;
      if (u.src_add && String(c[2] || "").indexOf(u.src_add) < 0) c[2] = (c[2] || "") + u.src_add;
    });
  }
  var S = window.SEA;
  if (S) {
    apply(S, false);
    S.checked = SC; S.checked_on = "2026-11-13"; S.version = "1.1";
    var b = (S.groups || []).filter(function (x) { return x.k === "BN-FW"; })[0];
    if (b) {
      b.n = "Brunei · construction and farm workers"; b.n_id = "Brunei · pekerja konstruksi dan pertanian";
      b.basis = "Workers on a labor licence held by the employer, mostly from Indonesia, the Philippines, Bangladesh and India. Domestic workers are excluded from the Employment Act (s. 2) and will be coded as a separate group.";
      b.basis_id = "Pekerja dengan lisensi tenaga kerja yang dipegang majikan, sebagian besar dari Indonesia, Filipina, Bangladesh dan India. Pekerja rumah tangga dikecualikan dari Employment Act (s. 2) dan akan dikodekan sebagai kelompok tersendiri.";
    }
    (S.changelog = S.changelog || []).unshift(["2026-11-13", "1.1", "All 80 destination cells checked on official legislation sites (ministry pages as official guidance): %d of 80 confirmed or partly confirmed and now P; the other cells stay S (5 Thai cells could not be reached, the rest rest on inference rather than an official text). Recodes: Malaysia domestic workers working time 0 to 1; Singapore Work Permit changing employer 0 to 1; Thailand recruitment fees 1 to 2 (MOU and farm workers) and fishers' social insurance 1 to 2; Brunei narrowed to construction and farm workers (coverage 1 to 2, changing employer 0 to 1, association unclear to 1, family 0 to 1). Notes rewritten from the official texts with links.", "Seluruh 80 sel negara tujuan diperiksa di situs legislasi resmi (halaman kementerian sebagai panduan resmi): %d dari 80 terkonfirmasi atau terkonfirmasi sebagian dan kini P; sel lainnya tetap S (5 sel Thailand tidak bisa dijangkau, sisanya bersandar pada inferensi, bukan teks resmi). Pengodean ulang: waktu kerja PRT Malaysia 0 ke 1; pindah majikan Work Permit Singapura 0 ke 1; biaya rekrutmen Thailand 1 ke 2 (pekerja MOU dan pertanian) dan jaminan sosial nelayan 1 ke 2; Brunei dipersempit ke pekerja konstruksi dan pertanian (cakupan 1 ke 2, pindah majikan 0 ke 1, berserikat belum jelas ke 1, keluarga 0 ke 1). Catatan ditulis ulang dari teks resmi dengan tautan."]);
  }
  var O = window.OC, FX = %s;
  if (O) {
    apply(O, true);
    for (var id in FX) { var a = id.split("."), c = ((O.codes || {})[a[0]] || {})[a[1]]; if (!c) continue; var x = FX[id]; if (x[1] != null) c[0] = x[1]; c[1] = x[2]; c[2] = x[3]; OCC[id] = x[0]; }
    if (O.changelog && !O._seaCheck) { O._seaCheck = 1; O.version = "1.4"; O.changelog.unshift(["2026-11-13", "1.4", "Indonesia, the Philippines and Vietnam (27 cells) and Myanmar, Cambodia, Laos and Timor-Leste checked on official legislation sites (ministry pages as official guidance, marked partly). Notes and sources updated to current instruments (for example KP2MI Regulation 17/2025 replacing BP2MI Regulation 9/2020; Philippine household-worker minimum age 23; Vietnam Decision 34/2025 and Decree 283/2026). Recodes: Indonesia pre-departure orientation 2 to 1 and Vietnam reintegration 2 to 1 (no text makes orientation free or assigns a duty to provide services); Myanmar exit unclear to 1 and reintegration 0 to 1; Cambodia and Laos welfare 0 to 1; Timor-Leste contract 2 to 0, orientation 2 to 1, welfare unclear to 0.", "Indonesia, Filipina dan Vietnam (27 sel) serta Myanmar, Kamboja, Laos dan Timor-Leste diperiksa di situs legislasi resmi (halaman kementerian sebagai panduan resmi, ditandai sebagian). Catatan dan sumber diperbarui ke instrumen terkini (misalnya Peraturan KP2MI 17/2025 menggantikan Peraturan BP2MI 9/2020; usia minimum PRT Filipina 23; Keputusan 34/2025 dan Dekret 283/2026 Vietnam). Pengodean ulang: orientasi pra-keberangkatan Indonesia 2 ke 1 dan reintegrasi Vietnam 2 ke 1; keluar Myanmar belum jelas ke 1 dan reintegrasi 0 ke 1; dana kesejahteraan Kamboja dan Laos 0 ke 1; Timor-Leste kontrak 2 ke 0, orientasi 2 ke 1, dana kesejahteraan belum jelas ke 0."]); }
    O.checked = O.checked || {}; for (var k in OCC) O.checked[k] = OCC[k]; O.checked_on = "2026-11-13";
  }
})();
""" % (json.dumps(upd, ensure_ascii=False), json.dumps(sea_checked), json.dumps(oc_checked), len(sea_checked), len(sea_checked), json.dumps(json.load(open(os.path.join(HERE, "origin_fixes.json"), encoding="utf-8")), ensure_ascii=False))
open(os.path.join(HERE, "sea-check.js"), "w", encoding="utf-8").write(js)
with open(os.path.join(HERE, "imac-check", "editor-questions.csv"), "w", newline="", encoding="utf-8-sig") as fh:
    w = csv.DictWriter(fh, fieldnames=["group", "feature", "coded", "check_finding", "source_tier", "question", "official_link"])
    w.writeheader(); w.writerows(questions)
print("SEA checked", len(sea_checked), "OC checked", len(oc_checked), "updates", len(upd), "questions", len(questions))
